<?php

namespace Database\Seeders;

use App\Models\Business;
use App\Models\User;
use Illuminate\Database\Seeder;
use Illuminate\Support\Str;
use Spatie\Permission\Models\Permission;
use Spatie\Permission\Models\Role;

class DatabaseSeeder extends Seeder
{
    public function run(): void
    {
        $this->call(AmroChickenMenuSeeder::class);

        foreach (['super_admin', 'business_admin', 'panel_user'] as $role) {
            Role::findOrCreate($role, 'web');
        }

        // First admin. Set ADMIN_EMAIL / ADMIN_PASSWORD in .env before seeding.
        $email = env('ADMIN_EMAIL', 'admin@amro-chicken.local');
        $password = env('ADMIN_PASSWORD');
        $admin = User::firstOrCreate(['email' => $email], [
            'name' => 'Amro Chicken Admin',
            'password' => $password ?: ($generated = Str::password(16)),
        ]);
        $admin->assignRole('super_admin');

        // Super admin gets every permission (generated by `php artisan shield:generate --all`).
        Role::findByName('super_admin', 'web')->syncPermissions(Permission::all());

        $business = Business::where('slug', 'amro-chicken')->first();
        if ($business && ! $admin->businesses()->whereKey($business->id)->exists()) {
            $admin->businesses()->attach($business->id, ['created_by' => $admin->id]);
        }

        if (isset($generated)) {
            $this->command?->warn("Admin {$email} created with password: {$generated} (change it after first login)");
        }
    }
}
